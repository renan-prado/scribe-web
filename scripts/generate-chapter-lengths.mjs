#!/usr/bin/env node
/**
 * Regenerate lib/bibles/chapter-lengths.ts from NVI.json.
 *
 * Verse counts are canon-stable across the shipped translations, so any of
 * them works as source; NVI was picked for parity with DEFAULT_TRANSLATION.
 *
 * Run manually when a translation JSON is added/updated:
 *   node scripts/generate-chapter-lengths.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "..", "lib", "bibles", "NVI.json");
const out = resolve(here, "..", "lib", "bibles", "chapter-lengths.ts");

const bible = JSON.parse(readFileSync(src, "utf8"));

const lines = [
  "/**",
  " * Verse counts per chapter for each protestant-canon book. Numbers are",
  " * standardized across all translations shipped in lib/bibles/*.json, so this",
  " * file is derived from NVI at build time but valid for any.",
  " *",
  " * Generated by scripts/generate-chapter-lengths.mjs. Do NOT edit by hand —",
  " * the source of truth is lib/bibles/NVI.json.",
  " */",
  "",
  "export const CHAPTER_VERSE_COUNTS: Record<string, number[]> = {",
];
for (const book of bible) {
  lines.push(
    `  ${JSON.stringify(book.abbrev)}: [${book.chapters.map((c) => c.length).join(", ")}],`
  );
}
lines.push("};", "");

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${lines.length} lines to ${out}`);
